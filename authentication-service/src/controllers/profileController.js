const fs = require("fs/promises");
const path = require("path");

const User = require("../models/User");
const { authenticateCurrentUser } = require("../middlewares/authMiddleware");

const {
  parseImage,
  saveImage,
  deleteImage,
} = require("../utils/profilePictureStorage");

const updateProfilePicture = async (args) => {
  let newFilename = null;

  try {
    const { token, imageData, mimeType } = args || {};

    // 1. Authenticate the current user
    const authenticatedUser = await authenticateCurrentUser(token);

    // 2. Validate the image (type, size, Base64, real file signature)
    const image = parseImage(imageData, mimeType);

    if (!image.ok) {
      return { success: false, message: image.message };
    }

    // 3. Find the authenticated user BEFORE touching the disk
    const user = await User.findByPk(authenticatedUser.userId);

    if (!user) {
      return { success: false, message: "User not found." };
    }

    // 4. Store the new image and update the database
    const oldPicture = user.profilePicture;

    newFilename = await saveImage(image.buffer, image.extension);

    user.profilePicture = newFilename;
    await user.save();

    // The database now points to the new file: it must not be cleaned up anymore
    const savedFilename = newFilename;
    newFilename = null;

    // 5. Remove the old picture
    if (oldPicture && oldPicture !== savedFilename) {
      await deleteImage(oldPicture);
    }

    return {
      success: true,
      message: "Profile picture updated successfully.",
      profilePicture: savedFilename,
    };
  } catch (error) {
    // Clean up the new file if the database update failed
    if (newFilename) {
      await deleteImage(newFilename);
    }

    console.error("Update profile picture error:", error);

    if (
      error.name === "JsonWebTokenError" ||
      error.name === "TokenExpiredError" ||
      error.message === "Access denied." ||
      error.message === "Authentication token is required."
    ) {
      return {
        success: false,
        message: "Unauthorized: a valid authentication token is required.",
      };
    }

    return {
      success: false,
      message: "Failed to update profile picture.",
    };
  }
};

const getProfilePicture = async (args) => {
  try {
    const { token } = args || {};

    // 1. Authenticate the current user
    const authenticatedUser = await authenticateCurrentUser(token);

    // 2. Find the user in the database
    const user = await User.findByPk(authenticatedUser.userId);

    if (!user) {
      return {
        success: false,
        message: "User not found.",
      };
    }

    // 3. Check whether the user has a profile picture
    const filename = user.profilePicture;

    if (!filename) {
      return {
        success: false,
        message: "No profile picture found.",
      };
    }

    // 4. Allow only filenames generated by our upload operation
    if (typeof filename !== "string" || path.basename(filename) !== filename) {
      return {
        success: false,
        message: "Invalid profile picture reference.",
      };
    }

    const mimeTypes = {
      jpg: "image/jpeg",
      png: "image/png",
      webp: "image/webp",
    };

    const extension = path.extname(filename).slice(1).toLowerCase();
    const mimeType = mimeTypes[extension];

    if (!mimeType) {
      return {
        success: false,
        message: "Unsupported profile picture format.",
      };
    }

    // 5. Read the image from disk
    const uploadDir = path.resolve(__dirname, "../../uploads/profile-pictures");

    const imagePath = path.join(uploadDir, filename);
    const imageBuffer = await fs.readFile(imagePath);

    // 6. Return the image as Base64 for SOAP
    return {
      success: true,
      message: "Profile picture retrieved successfully.",
      mimeType,
      imageData: imageBuffer.toString("base64"),
    };
  } catch (error) {
    console.error("Get profile picture error:", error);

    if (
      error.name === "JsonWebTokenError" ||
      error.name === "TokenExpiredError" ||
      error.message === "Access denied." ||
      error.message === "Authentication token is required."
    ) {
      return {
        success: false,
        message: "Unauthorized: a valid authentication token is required.",
      };
    }

    if (error.code === "ENOENT") {
      return {
        success: false,
        message: "Profile picture file not found.",
      };
    }

    return {
      success: false,
      message: "Failed to retrieve profile picture.",
    };
  }
};

module.exports = {
  updateProfilePicture,
  getProfilePicture,
};
